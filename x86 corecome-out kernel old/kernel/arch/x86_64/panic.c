#include "x86.h"

void panic(const char *msg) {
    serial_putc(COM1, 'P');
    serial_putc(COM1, 'A');
    serial_putc(COM1, 'N');
    serial_putc(COM1, 'I');
    serial_putc(COM1, 'C');
    serial_putc(COM1, ':');
    const char *p = msg;
    while (*p) serial_putc(COM1, *p++);
    serial_putc(COM1, '\n');
    cli();
    for (;;) hlt();
}
