struct idt_gate idt[IDT_N];
struct idt_ptr idtp;

extern void isr_common_stub(void);
extern void *isr_stub_table[IDT_N];

static void gate_pack(int n, void *handler, uint8_t ist, uint8_t dpl) {
    uint64_t h = (uint64_t)handler;
    idt[n].off_low  = (uint16_t)(h & 0xFFFF);
    idt[n].sel       = 0x08;
    idt[n].ist       = ist & 7;
    idt[n].rsv       = 0;
    idt[n].type      = 0xE;        /* 64-bit interrupt gate */
    idt[n].s         = 0;          /* S=0 ?? */
    idt[n].dpl       = dpl & 3;
    idt[n].p         = 1;
    idt[n].off_mid   = (uint16_t)((h >> 16) & 0xFFFF);
    idt[n].off_hi    = (uint32_t)(h >> 32);
    idt[n].zero      = 0;
}

void idt_set(int n, void *handler, uint8_t ist, uint8_t dpl) {
    gate_pack(n, handler, ist, dpl);
}

