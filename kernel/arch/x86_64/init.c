void alpos_arch_early_init(uint64_t mbi_phys) {
    (void)mbi_phys;
    console_init();
    kputs("[alpOS/x86_64] early init\n");
}

void alpos_arch_init(void) {
    gdt_init();
    idt_init();
    pic_init(0x20);
    paging_init(0x200000, 128ULL * 1024 * 1024);
    irq_install();
    pic_unmask(0);
    kputs("[alpOS/x86_64] arch init done\n");
}

