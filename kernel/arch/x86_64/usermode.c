#include "x86.h"

void user_jump(uint64_t entry, uint64_t sp, uint64_t arg) {
    (void)arg;

    /*
 * * ??? 16 ????System V ABI ??? rsp ?????????
 * * ?? CS/SS ? RPL ? 3IRET ?? RPL=3 ??????????
     */
    uint64_t user_rsp = (sp & ~15ULL) - 8;
    if (user_rsp < USER_BASE || user_rsp >= USER_TOP)
        panic("user_jump: stack out of user window");

    tss_set_rsp0((uint64_t)0);            /* ????????????M0 ? 0 */

    __asm volatile (
        "cli\n\t"
        "pushq $0x23\n\t"                 /* SS  (DPL=3, RPL=3) */
        "pushq %0\n\t"                    /* RSP */
        "pushq $0x202\n\t"                /* RFLAGS: IF=1 */
        "pushq $0x1B\n\t"                 /* CS  (DPL=3, RPL=3) */
        "pushq %1\n\t"                    /* RIP = entry */
        "swapgs\n\t"
        "iretq"
        : : "r"(user_rsp), "r"(entry) : "memory");
    __builtin_unreachable();
}
